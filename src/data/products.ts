export const getProductBySlug = (slug: string): Product | undefined =>
  products.find((p) => p.slug === slug);

export const getProductsByCategory = (category: string): Product[] =>
  products.filter((p) => p.category === category);

export const getFeaturedProducts = (): Product[] =>
  products.filter((p) => p.isHot).slice(0, 8);

export const getNewArrivals = (): Product[] =>
  [...products].sort((a, b) => b.createdAt.localeCompare(a.createdAt)).slice(0, 8);

export const getBestSellers = (): Product[] =>
  products.filter((p) => p.badges?.includes("bestseller")).slice(0, 4);

export const getRelatedProducts = (product: Product): Product[] =>
  products
    .filter((p) => p.category === product.category && p.id !== product.id)
    .slice(0, 4);